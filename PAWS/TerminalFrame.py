class TFrame(tk.Tk):
    """
    PAWS Terminal Frame — Tkinter implementation.

    This class creates the main window with a text display area, a command
    input field, a status bar, and a menu bar. It replaces the original
    wxPython implementation while preserving the same interface that Core.py's
    ClassTerminal expects (TDisplay, TInput, TStatusBar, etc.).
    """

    def __init__(self):
        """Initialize Terminal."""
        super().__init__()

        self.title("PAWS Terminal")
        self.geometry("829x786")

        #------------------------------
        # Create Menu Bar
        #------------------------------

        self._create_menu()

        #------------------------------
        # Create Status Bar
        #------------------------------

        self.TStatusBar = tk.Label(self, text="Status Bar Info Goes Here",
                                   bd=1, relief=tk.SUNKEN, anchor=tk.W,
                                   font=("Courier New", 12, "bold"))
        self.TStatusBar.pack(side=tk.BOTTOM, fill=tk.X)

        #------------------------------
        # Create Input Field
        #------------------------------

        self.TInput = tk.Entry(self, font=("Courier", 12, "bold"))
        self.TInput.pack(side=tk.BOTTOM, fill=tk.X)
        self.TInput.bind("<Return>", self.OnTInputTextEnter)
        self.TInput.config(state=tk.DISABLED)

        #------------------------------
        # Create Text Display
        #------------------------------

        # The text display is the main area where game output appears.
        # We use a tk.Text widget with word wrap and a "default" tag
        # for the initial styling.

        self.TDisplay = tk.Text(self, wrap=tk.WORD, font=("Arial", 12),
                                padx=5, pady=5)
        self.TDisplay.pack(fill=tk.BOTH, expand=True)
        self.TDisplay.config(state=tk.DISABLED)

        # Configure the default tag for normal text style
        self.TDisplay.tag_configure("default",
                                     font=("Arial", 12),
                                     foreground="white",
                                     background="black")

        # Insert initial message and disable editing
        self.TDisplay.config(state=tk.NORMAL)
        self.TDisplay.insert(tk.END,
            "To run a game, choose File \u2192 Pick Game \u2026 "
            "then choose a game from the list.", "default")
        self.TDisplay.config(state=tk.DISABLED)

        #------------------------------
        # Disable Unusable Menu Items
        #------------------------------

        # The following menu items can't be used until a game is selected
        # and running. The default for Tkinter menu items is enabled, so we
        # have to disable them before the menu can be used.

        self._set_menu_state("disabled")

    #********************************************************************************
    #                              Menu Creation
    #

    def _create_menu(self):
        """Create the menu bar with File, View, and Help menus."""

        menu_bar = tk.Menu(self)

        #--- File Menu ---

        file_menu = tk.Menu(menu_bar, tearoff=0)

        file_menu.add_command(label="Pick Game \u2026",
                              command=self.OnMenuFilePlaygameMenu)
        file_menu.add_separator()
        file_menu.add_command(label="Save",
                              command=self.OnMenuFileSaveMenu)
        file_menu.add_command(label="Restore",
                              command=self.OnMenuFileItems2Menu)
        file_menu.add_separator()
        file_menu.add_command(label="Debug",
                              command=self.OnMenuFileDebugMenu)
        file_menu.add_command(label="Log Game",
                              command=self.OnMenuFileLoggameMenu)
        file_menu.add_separator()
        file_menu.add_command(label="Verbose",
                              command=self.OnMenuFileVerboseMenu)
        file_menu.add_command(label="Terse",
                              command=self.OnMenuFileTerseMenu)
        file_menu.add_separator()
        file_menu.add_command(label="Exit",
                              command=self.OnMenuFileExitMenu)

        menu_bar.add_cascade(label="File", menu=file_menu)

        #--- View Menu ---

        view_menu = tk.Menu(menu_bar, tearoff=0)

        view_menu.add_command(label="Font \u2026",
                              command=self.OnMenuViewFontMenu)

        menu_bar.add_cascade(label="View", menu=view_menu)

        #--- Help Menu ---

        help_menu = tk.Menu(menu_bar, tearoff=0)

        help_menu.add_command(label="Hints",
                              command=self.OnMenuHelpHintsMenu)
        help_menu.add_command(label="About PAWS",
                              command=self.OnMenuHelpAboutMenu)

        menu_bar.add_cascade(label="Help", menu=help_menu)

        self.config(menu=menu_bar)

        # Store references so we can enable/disable items later
        self._menu_bar = menu_bar
        self._file_menu = file_menu
        self._view_menu = view_menu
        self._help_menu = help_menu

    def _set_menu_state(self, state):
        """
        Enable or disable the menu items that require a running game.

        state should be "disabled" (before game load) or "normal" (after
        game load). The Pick Game entry gets the opposite state.
        """
        # Pick Game is always available before a game, disabled after
        pick_state = "normal" if state == "disabled" else "disabled"

        # File menu: indices (0-based with separators)
        # 0 = Pick Game
        # 1 = separator
        # 2 = Save
        # 3 = Restore
        # 4 = separator
        # 5 = Debug
        # 6 = Log Game
        # 7 = separator
        # 8 = Verbose
        # 9 = Terse
        # 10 = separator
        # 11 = Exit

        self._file_menu.entryconfig(0, state=pick_state)    # Pick Game
        self._file_menu.entryconfig(2, state=state)          # Save
        self._file_menu.entryconfig(3, state=state)          # Restore
        self._file_menu.entryconfig(5, state=state)          # Debug
        self._file_menu.entryconfig(6, state=state)          # Log Game
        self._file_menu.entryconfig(8, state=state)          # Verbose
        self._file_menu.entryconfig(9, state=state)          # Terse

        # View menu
        self._view_menu.entryconfig(0, state=state)          # Font

        # Help menu
        self._help_menu.entryconfig(0, state=state)          # Hints

