    def OnTInputTextEnter(self, event=None):
        """
        This function is run when the player presses Enter after typing a
        command.
        """

        #-----------------------------
        # If Player JUST pressed Enter
        #-----------------------------

        # If the player hit the Enter key without typing a command we return
        # immediately. This allows the player to type another command.

        if not len(self.TInput.get()):
            return

        #-----------------------
        # Process Player's Input
        #-----------------------

        self.ProcessPlayerInput()

    def OnMenuFilePlaygameMenu(self):
        """
        This function is run when Play Game is clicked on the menu.
        """

        #------------------------------
        # Hook Frame into Core Terminal
        #------------------------------

        Terminal.Frame = self

        #----------------------
        # Ready The File Dialog
        #----------------------

        filename = filedialog.askopenfilename(
            title="Choose a game",
            initialdir=".",
            filetypes=[("PAWS Games (*.py)", "*.py"), ("All files", "*.*")]
        )

        # If the player clicked Cancel or didn't select a file, exit.
        if not filename:
            return

        #-------------------------
        # Retrieve the Game's Name
        #-------------------------

        # We need just the filename without path and without the .py extension.
        import os
        basename = os.path.basename(filename)
        Global.GameModule = basename[:-3]  # Strip .py extension

        if Global.GameModule == "LoadTerminal":
            self.TDisplay.config(state=tk.NORMAL)
            self.TDisplay.delete("1.0", tk.END)
            self.TDisplay.config(state=tk.DISABLED)
            Say("~p ~p ~p ~title ~lrd ~b LoadTerminal ~l is not a game.")
            return

        #------------------
        # Enable Menu Items
        #------------------

        self._set_menu_state("normal")

        #---------------------------------
        # Enable The Player's Command Box
        #---------------------------------

        self.TInput.config(state=tk.NORMAL)
        self.TInput.delete(0, tk.END)
        self.TInput.focus_set()

        # Set the default font for Terminal
        Terminal.CurrentFont = ("Arial", 12)

        #------------
        # Import Game
        #------------

        STMT = "from %s import *" % Global.GameModule
        exec(STMT, globals())

        #-------------------
        # Start Running Game
        #-------------------

        Engine.SetUpGame()
        Global.GameState = RUNNING
        Say("~p " + P.AP().Prompt())

    def OnMenuViewFontMenu(self, event=None):
        """
        Change the font used in the terminal. Called when Font... menu is
        clicked.

        Note: Tkinter does not have a built-in font dialog like wxPython's
        wx.FontDialog. This implementation provides a simple font selection
        dialog that lets the user choose font family and size.
        """

        #------------------------------
        # Hook Frame into Core Terminal
        #------------------------------

        Terminal.Frame = self

        #------------------------------
        # Simple Font Selection Dialog
        #------------------------------

        # Create a simple toplevel dialog for font selection
        font_dialog = tk.Toplevel(self)
        font_dialog.title("Select Font")
        font_dialog.geometry("300x350")
        font_dialog.transient(self)
        font_dialog.grab_set()

        # Get available font families
        available_families = sorted(tkfont.families(self))

        # Font family listbox
        tk.Label(font_dialog, text="Font Family:").pack(anchor=tk.W, padx=5)
        family_var = tk.StringVar(value="Arial")
        family_listbox = tk.Listbox(font_dialog, listvariable=family_var,
                                     height=10, exportselection=False)
        family_listbox.pack(fill=tk.BOTH, expand=True, padx=5)

        # Populate the listbox
        for family in available_families:
            family_listbox.insert(tk.END, family)

        # Set initial selection to current font family
        current_family = Terminal.CurrentFont[0] if Terminal.CurrentFont else "Arial"
        try:
            idx = available_families.index(current_family)
            family_listbox.selection_set(idx)
            family_listbox.see(idx)
        except ValueError:
            family_listbox.selection_set(0)

        # Font size spinbox
        tk.Label(font_dialog, text="Font Size:").pack(anchor=tk.W, padx=5, pady=(10, 0))
        size_var = tk.IntVar(value=Terminal.CurrentFontPitch)
        size_spinbox = tk.Spinbox(font_dialog, from_=8, to=36,
                                   textvariable=size_var, width=5)
        size_spinbox.pack(anchor=tk.W, padx=5)

        def apply_font():
            """Apply the selected font and close the dialog."""
            selection = family_listbox.curselection()
            if not selection:
                return

            chosen_family = available_families[selection[0]]
            chosen_size = size_var.get()

            Terminal.CurrentFontPitch = chosen_size
            Terminal.CurrentFont = (chosen_family, chosen_size)

            # Update the "default" tag to use the new font
            self.TDisplay.tag_configure("default",
                                         font=(chosen_family, chosen_size),
                                         foreground="white",
                                         background="black")

            # Update all existing style tags that use the default font size
            # to use the new font size. This is a simplification — it just
            # updates the base font for all tags that were created.
            for key, tag_name in Terminal._tag_cache.items():
                # Rebuild the font tuple with the new family/size
                old_font = self.TDisplay.tag_cget(tag_name, "font")
                # Parse style info and reconstruct
                self.TDisplay.tag_configure(tag_name,
                    font=(chosen_family, chosen_size))

            # Also update the TInput font
            self.TInput.config(font=(chosen_family, chosen_size, "bold"))

            font_dialog.destroy()

        def cancel_font():
            """Close the dialog without applying changes."""
            font_dialog.destroy()

        # Buttons
        btn_frame = tk.Frame(font_dialog)
        btn_frame.pack(fill=tk.X, padx=5, pady=5)
        tk.Button(btn_frame, text="OK", command=apply_font).pack(side=tk.LEFT, padx=5)
        tk.Button(btn_frame, text="Cancel", command=cancel_font).pack(side=tk.RIGHT, padx=5)

    def ProcessPlayerInput(self):
        """
        This function takes the player's typed input and processes it. First
        the parser is called, then the command text box is cleared. Then the
        parsed command is executed.
        """

        #--------------------------
        # Parse Player's Command(s)
        #--------------------------

        P.AP().GetPlayerInput()
        while P.AP().CommandsList:

            #------------------
            # Clear Command Box
            #------------------

            self.TInput.delete(0, tk.END)

            #-----------------------
            # Handle Pre-Turn Events
            #-----------------------

            Engine.PreTurnHandler()

            #-------------------------------
            # If Command Successfully Parsed
            #-------------------------------

            if P.AP().Parser() == SUCCESS:
                if Engine.TurnHandler() == TURN_ENDS:
                    Engine.AfterTurnHandler()

            #-------------------------------------------------
            # One turn finished, put a paragraph in the output
            #-------------------------------------------------

            Say("~n ")

            #---------------
            # Game Finished?
            #---------------

            if Global.GameState == FINISHED:
                Engine.PostGameWrapUp()
                Terminal.Terminate()

        #---------------------------
        # Display The Command Prompt
        #---------------------------

        Say("~n " + P.AP().Prompt())


